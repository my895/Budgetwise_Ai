import os
import sys
import subprocess
import argparse
from pathlib import Path


PROJECT_NAME = "Budget Tool MVP"
MIN_PYTHON_VERSION = (3, 9)

# Define directories to be created
DIRECTORIES_TO_CREATE = [
    "data/raw",
    "Checkpoints/logs",
    "Checkpoints/models",
    "Checkpoints/features",
    "Checkpoints/evaluation",
    "src/components",
    "src/models",
    "src/evaluation"
]

# Define project dependencies
BASIC_DEPS = ["pandas", "numpy", "scikit-learn", "streamlit", "pyyaml", "joblib", "plotly"]
ADVANCED_DEPS = ["xgboost", "tensorflow"]

# --- Helper Functions ---

def run_command(command: list, description: str):
    """Runs a shell command and provides user feedback."""
    print(f"   - {description}...", end="", flush=True)
    try:
        result = subprocess.run(
            command, 
            check=True, 
            capture_output=True, 
            text=True,
            encoding='utf-8' # Explicitly set encoding
        )
        print(" ✅")
        return True
    except subprocess.CalledProcessError as e:
        print(" ❌")
        print(f"\n      ERROR: {e.stderr}\n")
        return False
    except FileNotFoundError:
        print(" ❌")
        print(f"\n      ERROR: Command '{command[0]}' not found. Is it in your PATH?\n")
        return False

# --- Main Setup Steps ---

def welcome_banner():
    
    print(f" Setting up {PROJECT_NAME} ".center(60, "💰"))


def check_environment():
    """Checks for Python version and data file."""
    print("ℹ️  Phase 1: Checking Environment")
    
    # Check Python Version
    current_version = sys.version_info
    if current_version < MIN_PYTHON_VERSION:
        print(f"   - Checking Python version... ❌ (Required: {MIN_PYTHON_VERSION[0]}.{MIN_PYTHON_VERSION[1]}+, Found: {current_version.major}.{current_version.minor})")
        sys.exit(1)
    print(f"   - Checking Python version... ✅ ({current_version.major}.{current_version.minor})")

    # Check for user data
    data_file = Path("data/raw/data.csv")
    if not data_file.exists():
        print(f"   - Checking for user data file '{data_file}'... ⚠️")
        print(f"     Warning: Data file not found. Please add it before running the main application.")
    else:
        print(f"   - Checking for user data file '{data_file}'... ✅")

def setup_project_structure():
    """Creates the necessary directories for the project."""
    print("\nℹ️  Phase 2: Setting Up Project Structure")
    for directory in DIRECTORIES_TO_CREATE:
        Path(directory).mkdir(parents=True, exist_ok=True)
    print("   - All project directories created successfully. ✅")

def install_project_dependencies(install_all=False):
    """Installs basic and optionally advanced dependencies."""
    print("\nℹ️  Phase 3: Installing Dependencies")
    deps = BASIC_DEPS
    if install_all:
        deps += ADVANCED_DEPS
        print("   - Mode: Installing all basic and advanced libraries.")
    else:
        print("   - Mode: Installing basic libraries. Use --all-deps for more.")

    for dep in deps:
        if not run_command([sys.executable, "-m", "pip", "install", dep], f"Installing {dep}"):
            print(f"   - Halting setup due to installation failure on '{dep}'.")
            sys.exit(1)

def run_data_pipeline():
    """Runs the initial data ingestion and preprocessing steps."""
    print("\nℹ️  Phase 4: Running Initial Data Pipeline")
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    
    try:
        from src.components.data_ingestion import DataIngestion
        from src.components.data_preprocessing import DataPreprocessing
        
        print("   - Running Data Ingestion...")
        ingestion = DataIngestion()
        if ingestion.initiate_data_ingestion() is None:
            raise RuntimeError("Data ingestion failed. Check logs/ingestion.log.")
        print("     ...Ingestion complete. ✅")

        print("   - Running Data Preprocessing...")
        preprocessor = DataPreprocessing()
        if preprocessor.initiate_preprocessing() is None:
            raise RuntimeError("Data preprocessing failed. Check logs/preprocessing.log.")
        print("     ...Preprocessing complete. ✅")

    except (ImportError, RuntimeError) as e:
        print(f"   - Pipeline execution failed: {e} ❌")
        print("     Please ensure all component scripts exist and the data file is correct.")
        sys.exit(1)


def display_final_message():
    """Shows the user what to do next."""
    print("\n" + "="*60)
    print("🎉 SETUP COMPLETE! 🎉".center(60))
    print("="*60)
    print("You're all set. To get started, run the main workflow:")
    print("\n    python quick_start.py\n")
    print("This will train the models and launch the interactive dashboard.")
    print("="*60)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=f"Setup script for {PROJECT_NAME}.")
    parser.add_argument("--all-deps", action="store_true", help="Install all advanced ML/DL dependencies.")
    parser.add_argument("--skip-pipeline", action="store_true", help="Skip the initial data processing pipeline.")
    args = parser.parse_args()
    
    welcome_banner()
    check_environment()
    setup_project_structure()
    install_project_dependencies(args.all_deps)
    
    if not args.skip_pipeline:
        run_data_pipeline()
    else:
        print("\nℹ️  Skipping initial data pipeline as requested.")
        
    generate_quick_start()
    display_final_message()